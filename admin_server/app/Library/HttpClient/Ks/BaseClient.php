<?php

declare(strict_types=1);

namespace App\Library\HttpClient\Ks;

use App\Library\HttpClient\ClientAbstract;
use App\Model\AppCompany;
use App\ModelTools\PlacementAccount;

abstract class BaseClient extends ClientAbstract
{
    protected $conf = [];

    protected $time = 0;

    public function getClientName(): string
    {
        return 'ks';
    }

    public function setAccount(int $accountId)
    {
        $conf = AppCompany::select('media_conf_ks')->where('company_id', $accountId)->first();
        $this->conf = data_get($conf, 'media_conf_ks');
        return $this;
    }

    public function setConf($conf)
    {
        $this->conf = $conf;
        return $this;
    }

    public function setTImestamp(int $time)
    {
        $this->time = $time;
        return $this;
    }

    public function request(string $method, string $uri, array $params = [])
    {
        $ak = $this->conf['user_id'];
        $sk = $this->conf['secret'];
        $queryParams = [
            'ak' => $ak,
            'timestamp' => $this->time > 0 ? $this->time:time()
        ];
        if(strtoupper($method) == 'GET') {
            $queryParams = array_merge($queryParams, $params);
        }
        $sign = $this->getSign($uri, $sk, $queryParams);
        $queryParams['sign'] = $sign;
        $queryParams = http_build_query($queryParams);
        $uri = "{$uri}?{$queryParams}";

        return parent::request($method, $uri, $params); // TODO: Change the autogenerated stub
    }

    protected function getSign($api_link, $sk, $params): string
    {
        $params['sk'] = $sk;
        ksort($params);
        $params = http_build_query($params);
        $str = $api_link . '?' . $params;
        return md5($str);
    }

    protected function buildHeader(): array
    {
        return []; // TODO: Change the autogenerated stub
    }
}