<?php

declare(strict_types=1);

namespace App\Library\HttpClient\Ubapi;

use App\Library\HttpClient\ClientAbstract;
use App\Model\AppCompany;

abstract class BaseClient extends ClientAbstract
{
    protected $conf = [];

    public function getClientName(): string
    {
        return 'ubapi';
    }

    public function setAccount(int $accountId)
    {
        $conf = AppCompany::select('media_conf_bd')->where('company_id', $accountId)->first();
        $this->conf = data_get($conf, 'media_conf_bd');
        return $this;
    }

    public function setConf($conf)
    {
        $this->conf = $conf;
        return $this;
    }

    public function request(string $method, string $uri, array $params = [])
    {
        $timestamp = time();
        if(strtoupper($method) == 'GET') {
            $contentType = '';
            $bodyMd5 = '';
            $uri = $uri . '?' . urldecode(http_build_query($params));
        }else{
            $contentType = 'application/json';
            $bodyMd5 = md5(json_encode($params));
        }
        $message = $this->conf['user_id'] . "\n" . strtoupper($method) . "\n" . $uri . "\n" . $timestamp . "\n" . $contentType . "\n" . $bodyMd5;
        $privateKey = $this->formatKey($this->conf['secret'], 'private');
        $binarySignature = '';
        @openssl_sign($message, $binarySignature, openssl_get_privatekey($privateKey), OPENSSL_ALGO_SHA1);
        $option = [
            'headers' => [
                'x-ub-date' => $timestamp,
                'x-ub-authorization' => $this->conf['user_id'] . ':' . base64_encode($binarySignature),
            ],
            'json' => strtoupper($method) == 'GET'?[]:$params,
        ];
        return parent::request($method, $uri, $option); // TODO: Change the autogenerated stub
    }

    protected function getSign($api_link, $sk, $params): string
    {
        $params['sk'] = $sk;
        ksort($params);
        $params = http_build_query($params);
        $str = $api_link . '?' . $params;
        return md5($str);
    }

    protected function buildHeader(): array
    {
        return []; // TODO: Change the autogenerated stub
    }

    protected function formatKey(string $key, string $type = 'private')
    {
        // 秘钥标识
        $code = $type === 'public' ? 'PUBLIC' : 'DSA PRIVATE';
        // 格式化
        $format = sprintf("-----BEGIN %s KEY-----", $code);
        $format .= "\n" . chunk_split($key, 64, "\n");
        $format .= sprintf("-----END %s KEY-----", $code);
        // 返回
        return $format;
    }
}